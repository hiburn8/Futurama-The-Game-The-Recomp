"""Compiles src/render/xd3d/fixedfunction.hlsl ahead of time into src/render/xd3d/ShaderBlobs.h (the DXBC of its six
entry points as byte arrays, plus the SHA-256 of the source they came from) with fxc, the Windows SDK's HLSL compiler
(the same compiler D3DCompile is; /O3 as the former run-time D3DCOMPILE_OPTIMIZATION_LEVEL3).

  python tools/compile_shaders.py [--fxc <path>]

The build checks the header against the source: src/CMakeLists.txt hashes fixedfunction.hlsl (LF line endings) into
FUT_SHADER_SOURCE_SHA256 and D3D11Device.cpp static_asserts it equals the header's. Commit both files together.
"""
import argparse
import glob
import hashlib
import pathlib
import subprocess
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'src/render/xd3d/fixedfunction.hlsl'
HEADER = ROOT / 'src/render/xd3d/ShaderBlobs.h'
ENTRIES = [('VSMain', 'vs_4_0'), ('PSMain', 'ps_4_0'), ('ClearVS', 'vs_4_0'), ('ClearPS', 'ps_4_0'),
           ('BlitVS', 'vs_4_0'), ('BlitPS', 'ps_4_0')]


def find_fxc():
    hits = glob.glob(r'C:\Program Files (x86)\Windows Kits\10\bin\10.*\x64\fxc.exe')
    if not hits:
        sys.exit('fxc.exe not found (the Windows 10/11 SDK); pass --fxc')
    return sorted(hits, key=lambda p: [int(x) for x in pathlib.Path(p).parts[-3].split('.')])[-1]


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--fxc', default=None)
    args = ap.parse_args()
    fxc = args.fxc or find_fxc()
    source = SOURCE.read_bytes().replace(b'\r\n', b'\n')
    sha = hashlib.sha256(source).hexdigest()
    blobs = {}
    with tempfile.TemporaryDirectory() as tmp:
        for entry, profile in ENTRIES:
            out = pathlib.Path(tmp) / (entry + '.cso')
            subprocess.run([fxc, '/nologo', '/T', profile, '/E', entry, '/O3', '/Fo', str(out), str(SOURCE)],
                           check=True)
            blobs[entry] = out.read_bytes()
            if blobs[entry][:4] != b'DXBC':
                sys.exit('%s: fxc did not produce DXBC' % entry)
    lines = ['// Generated by tools/compile_shaders.py from fixedfunction.hlsl with fxc (%s): the DXBC of its entry'
             % pathlib.Path(fxc).parts[-3],
             '// points. Do not edit; edit the .hlsl and run the tool (the build checks the source hash below).',
             '#pragma once', '', 'namespace fut::render::xd3d::shaders {', '',
             '// SHA-256 of fixedfunction.hlsl (LF line endings) these were compiled from.',
             'inline constexpr char kSourceSha256[] = "%s";' % sha, '']
    for entry, _ in ENTRIES:
        data = blobs[entry]
        lines.append('inline constexpr unsigned char k%s[%d] = {' % (entry, len(data)))
        for i in range(0, len(data), 24):
            lines.append('    ' + ', '.join('0x%02X' % b for b in data[i:i + 24]) + ',')
        lines += ['};', '']
    lines += ['}  // namespace fut::render::xd3d::shaders', '']
    HEADER.write_text('\n'.join(lines), encoding='utf-8', newline='\n')
    print('wrote %s: %s' % (HEADER.relative_to(ROOT), ', '.join('%s %d B' % (e, len(blobs[e])) for e, _ in ENTRIES)))
    print('source sha256 %s' % sha)


if __name__ == '__main__':
    main()
