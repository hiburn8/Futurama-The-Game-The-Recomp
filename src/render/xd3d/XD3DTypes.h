struct D3DMATRIX {                                    // row-major, row vectors (v * M)
    f32 m[4][4];
};

struct D3DVIEWPORT8 {
    u32 X = 0, Y = 0, Width = 0, Height = 0;
    f32 MinZ = 0, MaxZ = 1;
};

struct D3DRECT {
    s32 x1, y1, x2, y2;
};

struct D3DMATERIAL8 {                                 // 17 dwords: diffuse, ambient, specular, emissive (rgba), power
    f32 diffuse[4], ambient[4], specular[4], emissive[4];
    f32 power;
};

struct D3DLIGHT8 {                                    // 26 dwords
    u32 type;
    f32 diffuse[4], specular[4], ambient[4];
    f32 position[3], direction[3];
    f32 range, falloff, attenuation0, attenuation1, attenuation2, theta, phi;
};
static_assert(sizeof(D3DMATERIAL8) == 17 * 4 && sizeof(D3DLIGHT8) == 26 * 4);

// The Xbox D3DFORMAT's bits a texel (the renderer's 0x00158820: 8 / 16 / 32, -1 for the compressed formats; here
// DXT1 4 and DXT3 / DXT5 8 for the sizes) and whether it is swizzled (0x00158A20).
u32 FormatBits(u32 format);
bool FormatSwizzled(u32 format);
inline bool FormatCompressed(u32 format) { return format == 0xC || format == 0xE || format == 0xF; }
// A level's bytes in the texture's memory (the compressed formats in 4 x 4 blocks).
size_t LevelBytes(u32 format, u32 width, u32 height);

